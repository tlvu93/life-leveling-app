const fs = require("fs");
const path = require("path");
const {
  withAppBuildGradle,
  withDangerousMod,
} = require("expo/config-plugins");

const CXX_MARKER = "// @generated by with-android-build-setup";
const CXX_DIRECTORY_SETUP = [
  CXX_MARKER,
  'def lifeLevelingCxxBuildDir = System.getenv("LIFE_LEVELING_CXX_DIR")',
  'if (!lifeLevelingCxxBuildDir && System.getProperty("os.name").toLowerCase().contains("windows")) {',
  '    lifeLevelingCxxBuildDir = "${rootDir.toPath().root}LifeLevelingBuild/cxx"',
  "}",
  "",
].join("\n");

const CXX_ANDROID_BLOCK = [
  "    if (lifeLevelingCxxBuildDir) {",
  "        externalNativeBuild {",
  "            cmake {",
  "                buildStagingDirectory lifeLevelingCxxBuildDir",
  "            }",
  "        }",
  "    }",
  "",
].join("\n");

function withShortWindowsCxxPath(config) {
  return withAppBuildGradle(config, (gradleConfig) => {
    let contents = gradleConfig.modResults.contents;

    if (!contents.includes(CXX_MARKER)) {
      contents = contents.replace("android {\n", `${CXX_DIRECTORY_SETUP}android {\n`);
      contents = contents.replace(
        "    compileSdk rootProject.ext.compileSdkVersion\n",
        `    compileSdk rootProject.ext.compileSdkVersion\n\n${CXX_ANDROID_BLOCK}`,
      );
    }

    gradleConfig.modResults.contents = contents;
    return gradleConfig;
  });
}

function withJava17Daemon(config) {
  return withDangerousMod(config, [
    "android",
    async (dangerousConfig) => {
      const propertiesPath = path.join(
        dangerousConfig.modRequest.platformProjectRoot,
        "gradle",
        "gradle-daemon-jvm.properties",
      );

      fs.mkdirSync(path.dirname(propertiesPath), { recursive: true });
      const current = fs.existsSync(propertiesPath)
        ? fs.readFileSync(propertiesPath, "utf8")
        : "#This file is generated by updateDaemonJvm\n";
      const next = /^toolchainVersion=.*$/m.test(current)
        ? current.replace(/^toolchainVersion=.*$/m, "toolchainVersion=17")
        : `${current.trimEnd()}\ntoolchainVersion=17\n`;

      fs.writeFileSync(propertiesPath, next);
      return dangerousConfig;
    },
  ]);
}

module.exports = function withAndroidBuildSetup(config) {
  config = withShortWindowsCxxPath(config);
  return withJava17Daemon(config);
};
